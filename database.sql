-- ==========================================
-- 9. CONSULTA PARA VER LAS ENTREGAS
-- ==========================================

SELECT
    e.nombre_apellido AS estudiante,
    c.nombre_curso,
    c.seccion,
    tp.asignatura,
    cal.puntos_obtenidos,
    tp.puntaje_total,
    cal.estado_logro,
    cal.enlace_web

FROM calificaciones cal

JOIN estudiantes e
    ON cal.estudiante_id = e.id

JOIN cursos c
    ON e.curso_id = c.id

JOIN trabajos_practicos tp
    ON cal.tp_id = tp.id;