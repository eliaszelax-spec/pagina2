-- ==========================================
-- BASE DE DATOS: BTI DESARROLLO WEB
-- Compatible con Supabase / PostgreSQL
-- ==========================================


-- ==========================================
-- 1. TABLA DE CURSOS / SECCIONES
-- ==========================================

CREATE TABLE cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_curso VARCHAR(50) NOT NULL,
    seccion VARCHAR(10) NOT NULL,
    turno VARCHAR(20)
);


-- ==========================================
-- 2. TABLA DE ESTUDIANTES
-- ==========================================

CREATE TABLE estudiantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_apellido VARCHAR(100) NOT NULL,
    curso_id BIGINT,

    CONSTRAINT fk_estudiante_curso
        FOREIGN KEY (curso_id)
        REFERENCES cursos(id)
);


-- ==========================================
-- 3. TABLA DE TRABAJOS PRÁCTICOS
-- ==========================================

CREATE TABLE trabajos_practicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    asignatura VARCHAR(100) NOT NULL,
    puntaje_total INT DEFAULT 30,
    fecha_entrega DATE
);


-- ==========================================
-- 4. TABLA DE CALIFICACIONES
-- ==========================================

CREATE TABLE calificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT,
    tp_id BIGINT,
    puntos_obtenidos INT,
    estado_logro VARCHAR(20),
    enlace_web VARCHAR(255),

    CONSTRAINT fk_calificacion_estudiante
        FOREIGN KEY (estudiante_id)
        REFERENCES estudiantes(id),

    CONSTRAINT fk_calificacion_tp
        FOREIGN KEY (tp_id)
        REFERENCES trabajos_practicos(id)
);


